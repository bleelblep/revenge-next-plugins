"""Moves the purchased ToffeeCraft pets out of SeasonalData.kt into assets/paid-pets.bin.

Run after tools/build_paid_seasonal.py (it calls this itself). SeasonalData.kt keeps the free pets
inline and a `paid("id")` slot for each purchased one, so the public source never holds the art. The
.bin is gzipped JSON scrambled with a SHA-256 keystream (PaidPets.kt reverses it). That only stops
casual copying, not someone who reads PaidPets.kt: it's obfuscation, not protection.

assets/paid-pets.bin is gitignored; the plugin ZIP carries it, and Revenge extracts it to
dist/<id>/paid-pets.bin.
"""
import gzip
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
KT = ROOT / "src" / "main" / "kotlin" / "com" / "bleelblep" / "sparkle" / "SeasonalData.kt"
BIN = ROOT / "assets" / "paid-pets.bin"
# Open assets (Turkeys CC0, Snowman CC-BY 3.0, Flappy Dragon CC0); everything else is purchased.
FREE = {"turkey", "snowman", "dragon"}
# Same bytes as PaidPets.KEY.
KEY = b"shimeji/seasonal/v1:6f1c2a9e4b7d"
MAGIC = b"SHP1"

PET = re.compile(r'^\t\tPet\("([^"]+)", "([^"]+)", (\d+), (\d+), mapOf\($')
STRIP = re.compile(r'^\t\t\t"([^"]+)" to \((\d+) to arrayOf\((.*)\)\),?$')
END = re.compile(r'^\t\t\)(?:, floatArrayOf\(([^)]*)\))?\),?$')


def keystream(n: int) -> bytes:
    out = bytearray()
    counter = 0
    while len(out) < n:
        out += hashlib.sha256(KEY + counter.to_bytes(8, "big")).digest()
        counter += 1
    return bytes(out[:n])


def scramble(data: bytes) -> bytes:
    return bytes(a ^ b for a, b in zip(data, keystream(len(data))))


def main():
    lines = KT.read_text(encoding="utf-8").splitlines()
    out, paid, i = [], {}, 0
    while i < len(lines):
        m = PET.match(lines[i])
        if not m:
            out.append(lines[i])
            i += 1
            continue
        pid, name, w, h = m.group(1), m.group(2), int(m.group(3)), int(m.group(4))
        block = [lines[i]]
        strips = []
        i += 1
        while True:
            line = lines[i]
            block.append(line)
            i += 1
            s = STRIP.match(line)
            if s:
                strips.append([s.group(1), int(s.group(2)), re.findall(r'"([^"]*)"', s.group(3))])
                continue
            e = END.match(line)
            if e:
                mouth = [float(v.strip().rstrip("f")) for v in e.group(1).split(",")] if e.group(1) else None
                break
            raise SystemExit(f"Unexpected line in {pid}: {line[:80]}")
        if pid in FREE:
            out.extend(block)
        else:
            paid[pid] = {"name": name, "w": w, "h": h, "mouth": mouth, "strips": strips}
            out.append(f'\t\tpaid("{pid}", "{name}", {w}, {h}),')
    if not paid:
        raise SystemExit("No purchased pets found (already split?)")

    text = "\n".join(out) + "\n"
    text = text.replace("// GENERATED by tools/build_paid_seasonal.py -- do not edit by hand.",
                        "// GENERATED by tools/build_paid_seasonal.py + tools/split_paid.py -- do not edit by hand.")
    text = text.replace("// Includes purchased ToffeeCraft artwork (project use only; not a reusable asset pack).",
                        "// Purchased ToffeeCraft pets are paid(...) slots; their art is in assets/paid-pets.bin, never in source.")
    # The slots read from PaidPets; when the .bin is missing (a build from the public source) they
    # keep their place, so saved pet ids stay the same, and borrow the Dragon's art.
    text = text.replace("\tval pets: List<Pet> = listOf(",
                        "\tprivate fun paid(id: String, name: String, w: Int, h: Int): Pet =\n"
                        "\t\tPaidPets[id]?.let { Pet(id, it.name, it.w, it.h, it.strips, it.mouth) } ?: Pet(id, name, w, h, emptyMap())\n\n"
                        "\tprivate fun withFallbacks(list: List<Pet>): List<Pet> {\n"
                        "\t\tval dragon = list.first { it.id == \"dragon\" }\n"
                        "\t\treturn list.map { if (it.strips.isEmpty()) Pet(it.id, it.name, dragon.w, dragon.h, dragon.strips) else it }\n"
                        "\t}\n\n"
                        "\tval pets: List<Pet> = listOf(")
    if not text.rstrip().endswith("\t)\n}"):
        raise SystemExit("Unexpected end of SeasonalData.kt")
    text = text.rstrip()[:-len("\t)\n}")] + "\t).let(::withFallbacks)\n}\n"
    KT.write_text(text, encoding="utf-8")

    BIN.parent.mkdir(parents=True, exist_ok=True)
    payload = gzip.compress(json.dumps(paid, separators=(",", ":")).encode("utf-8"), mtime=0)
    BIN.write_bytes(MAGIC + scramble(payload))
    print(f"Split {len(paid)} purchased pets into {BIN.relative_to(ROOT)} ({BIN.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
