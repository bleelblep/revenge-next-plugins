"""Embed art/gary runtime PNG strips and original Gary game vocals (Pillow required)."""
import base64
import json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
ART = ROOT / 'art/gary'
OUT = ROOT / 'src/main/kotlin/com/bleelblep/sparkle/GaryData.kt'

def chunks(path):
    data = base64.b64encode(path.read_bytes()).decode('ascii')
    return 'arrayOf(' + ', '.join('"' + data[i:i+50000] + '"' for i in range(0,len(data),50000)) + ')'

manifest = json.loads((ART / 'animations.json').read_text())
lines = ['// GENERATED by tools/build_gary.py. Sources: art/gary/*source-info.json.',
         'package com.bleelblep.sparkle', '', 'internal object GaryData {',
         '\tconst val W = 224', '\tconst val H = 194',
         '\tclass Strip(val times: IntArray, val png: Array<String>)',
         '\tval strips = mapOf(']
for clip in manifest['clips']:
    path = ART / (clip['id'] + '.png')
    with Image.open(path) as im:
        assert im.size == (224*len(clip['times']),194)
        assert im.mode == 'RGBA'
    times = ', '.join(map(str,clip['times']))
    lines.append(f'\t\t"{clip["id"]}" to Strip(intArrayOf({times}), {chunks(path)}),')
lines += ['\t)', '\tval sounds: Map<String, Array<String>> = mapOf(']
for path in sorted((ART / 'sounds').glob('*.ogg')):
    lines.append(f'\t\t"gary_{path.name}" to {chunks(path)},')
lines += ['\t)', '}', '']
OUT.write_text('\n'.join(lines), encoding='utf-8')
print('Embedded', len(manifest['clips']), 'Gary clips and', len(list((ART/'sounds').glob('*.ogg'))), 'vocals')
