"""
Builds src/main/kotlin/.../PetData.kt from LuizMelo's Pet Cats Pack and Pet Dogs Pack (CC0,
art/pet_cats, art/pet_dogs): six cats and six dogs, each with its own animation strips.

Each animation is a horizontal strip of square cells (cats 50 px, dogs 100 px) with a lot of empty
space round a small animal. Every pet is cropped to ONE box: the union of what's drawn in every frame
of every animation, so it never shifts between poses, and the box is padded so frames line up on
the same floor. Strips are re-encoded as palette PNGs and embedded as base64.

Usage, from the plugin folder:  python tools/build_pets.py [--preview]
"""
import base64
import io
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "main" / "kotlin" / "com" / "bleelblep" / "sparkle" / "PetData.kt"
CATS = ROOT / "art" / "pet_cats" / "Pet Cats Pack"
DOGS = ROOT / "art" / "pet_dogs" / "Pet Dogs Pack"
CHUNK = 60000

# id: (folder, display name, cell, {our name: file suffix})
CAT_ANIMS = {
	"idle": "Idle", "walk": "Walk", "run": "Run", "voice": "Meow", "lay": "Laying", "itch": "Itch",
	"sleep1": "Sleeping1", "sleep2": "Sleeping2", "sit": "Sitting", "lick1": "Licking 1",
	"lick2": "Licking 2", "stretch": "Stretching",
}
DOG_ANIMS = {
	"idle": "idle", "walk": "walk", "run": "run", "voice": "bark", "lay": "lying-down", "itch": "itching",
	"sleep1": "sleeping", "sit": "sitting", "lick1": "licking1", "lick2": "licking2", "stretch": "stretching",
}
PETS = [
	("cat_ginger", CATS / "Cat-1", "Ginger cat", 50, CAT_ANIMS),
	("cat_black", CATS / "Cat-2", "Black cat", 50, CAT_ANIMS),
	("cat_siamese", CATS / "Cat-3", "Siamese cat", 50, CAT_ANIMS),
	("cat_sphynx", CATS / "Cat-4", "Sphynx cat", 50, CAT_ANIMS),
	("cat_ragdoll", CATS / "Cat-5", "Ragdoll cat", 50, CAT_ANIMS),
	("cat_tabby", CATS / "Cat-6", "Grey tabby", 50, CAT_ANIMS),
	("dog_golden", DOGS / "Dog-1-Golden-Retriever", "Golden Retriever", 100, DOG_ANIMS),
	("dog_akita", DOGS / "Dog-2-Akita", "Akita", 100, DOG_ANIMS),
	("dog_dane", DOGS / "Dog-3-Great-Dane", "Great Dane", 100, DOG_ANIMS),
	("dog_schnauzer", DOGS / "Dog-4-Schnauzer", "Schnauzer", 100, DOG_ANIMS),
	("dog_bernard", DOGS / "Dog-5-Saint-Bernard", "Saint Bernard", 100, DOG_ANIMS),
	("dog_husky", DOGS / "Dog-6-Siberian-Husky", "Siberian Husky", 100, DOG_ANIMS),
]


def find(folder: Path, suffix: str) -> Path:
	for f in folder.glob("*.png"):
		stem = f.stem.lower()
		if stem.endswith("-" + suffix.lower()) or stem.endswith(" " + suffix.lower()):
			return f
	raise FileNotFoundError(f"{folder.name}: {suffix}")


def cells(path: Path, cell: int):
	strip = Image.open(path).convert("RGBA")
	return [strip.crop((i * cell, 0, (i + 1) * cell, cell)) for i in range(strip.width // cell)]


def main():
	lines = [
		"// GENERATED by tools/build_pets.py from art/pet_cats and art/pet_dogs -- do not edit by hand.",
		"// Pet Cats Pack and Pet Dogs Pack by LuizMelo (luizmelo.itch.io), CC0.",
		"",
		"package com.bleelblep.sparkle",
		"",
		"internal object PetData {",
		"\tclass Pet(override val id: String, override val name: String, override val w: Int, override val h: Int, override val strips: Map<String, Pair<Int, Array<String>>>) : SheetPet",
		"",
		"\tval pets: List<Pet> = listOf(",
	]
	previews = []
	for pid, folder, name, cell, anims in PETS:
		# Not every pet has every animation (the Siamese has no Itch); missing ones are left out and
		# SheetLook falls back to another.
		frames = {}
		for k, v in anims.items():
			try:
				frames[k] = cells(find(folder, v), cell)
			except FileNotFoundError:
				print(f"  {pid}: no {v}, skipped")
		# One box for every frame of every animation.
		box = None
		for fs in frames.values():
			for f in fs:
				b = f.getbbox()
				if b:
					box = b if box is None else (min(box[0], b[0]), min(box[1], b[1]), max(box[2], b[2]), max(box[3], b[3]))
		x0, y0, x1, y1 = box
		w, h = x1 - x0, y1 - y0
		strips = []
		for k, fs in frames.items():
			sheet = Image.new("RGBA", (w * len(fs), h), (0, 0, 0, 0))
			for i, f in enumerate(fs):
				sheet.alpha_composite(f.crop(box), (i * w, 0))
			buf = io.BytesIO()
			sheet.save(buf, "PNG", optimize=True)
			data = base64.b64encode(buf.getvalue()).decode("ascii")
			chunks = ", ".join(f'"{data[i:i + CHUNK]}"' for i in range(0, len(data), CHUNK))
			strips.append(f'"{k}" to ({len(fs)} to arrayOf({chunks}))')
			if k == "idle":
				previews.append((name, sheet.crop((0, 0, w, h))))
		lines.append(f'\t\tPet("{pid}", "{name}", {w}, {h}, mapOf(')
		lines += [f"\t\t\t{s}," for s in strips]
		lines.append("\t\t)),")
		print(f"{pid}: {w}x{h}, {sum(len(v) for v in frames.values())} frames")
	lines += ["\t)", "}", ""]
	OUT.write_text("\n".join(lines), encoding="utf-8")
	print(f"wrote {OUT.name}: {OUT.stat().st_size} bytes")

	if "--preview" in sys.argv:
		S = 6
		tw = max(p.width for _, p in previews) * S + 20
		th = max(p.height for _, p in previews) * S + 20
		img = Image.new("RGBA", (tw * 6, th * 2), (54, 57, 63, 255))
		for i, (_, p) in enumerate(previews):
			big = p.resize((p.width * S, p.height * S), Image.NEAREST)
			img.alpha_composite(big, ((i % 6) * tw + 10, (i // 6) * th + th - 10 - big.height))
		img.save(ROOT / "art" / "pets_cropped.png")
		print("wrote art/pets_cropped.png")


if __name__ == "__main__":
	main()
