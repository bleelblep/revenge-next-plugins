"""Writes the boss pets into the plugin: BossData.kt (strips as base64 PNG, like SeasonalData.kt) and
js/bossPets.ts (picker metadata), from the frames tools/boss_art.py draws.

Kept apart from SeasonalData.kt on purpose: that file is regenerated from the purchased ToffeeCraft
archives, which are not on every machine, and these pets need none of them. SheetLook lists
SeasonalData.pets then BossData.pets, so the boss ids follow the last purchased pet's.

Usage, from the plugin folder:  python tools/build_boss.py
"""
import base64
import io
import json
import re
from pathlib import Path

import boss_art

ROOT = Path(__file__).resolve().parent.parent
KT_DIR = ROOT / "src" / "main" / "kotlin" / "com" / "bleelblep" / "sparkle"
KT = KT_DIR / "BossData.kt"
TS = ROOT / "js" / "bossPets.ts"
CHUNK = 60000
FIRST_SEASONAL = 15

# id, label, pack, default name, how it leaves, mouth (pet pixels), refW (the body's width the size
# setting measures; the Horseman's cell is 64 wide for the scythe's sake), idle fps.
BOSSES = [
	("horseman", "Headless Horseman", "halloween", "Hollow", "sinks into the floor", boss_art.HM_MOUTH, 44, 4.0, boss_art.horseman_anims),
	("krampus", "Krampus", "christmas", "Krampus", "drops through the floor", boss_art.KR_MOUTH, 44, 4.0, boss_art.krampus_anims),
]


def encode(frames):
	s = boss_art.strip(frames)
	buf = io.BytesIO()
	s.save(buf, "PNG", optimize=True)
	data = base64.b64encode(buf.getvalue()).decode("ascii")
	chunks = ", ".join(f'"{data[j:j + CHUNK]}"' for j in range(0, len(data), CHUNK))
	return f"({len(frames)} to arrayOf({chunks}))"


def pet_lines(pid, name, anims, mouth, ref_w, idle_fps):
	frames0 = next(iter(anims.values()))[0]
	w, h = frames0[0].size
	assert all(f.size == (w, h) for fs, _ in anims.values() for f in fs), pid
	lines = [f'\t\tPet("{pid}", "{name}", {w}, {h}, mapOf(']
	for key, (frames, _fps) in anims.items():
		lines.append(f'\t\t\t"{key}" to {encode(frames)},')
	m = f"floatArrayOf({mouth[0] + 0.5:.1f}f, {mouth[1] + 0.5:.1f}f)" if mouth else "null"
	lines.append(f"\t\t), {m}, {ref_w}, {idle_fps:.1f}f),")
	return lines, (w, h)


def main():
	seasonal = (KT_DIR / "SeasonalData.kt").read_text(encoding="utf-8")
	count = len(re.findall(r'^\t\tPet\("', seasonal, re.M))
	assert count >= 17, count
	first_id = FIRST_SEASONAL + count

	lines = [
		"// GENERATED by tools/build_boss.py from the frames tools/boss_art.py draws -- do not edit by hand.",
		"// Original art for Shimeji, drawn in code; no third-party assets.",
		"",
		"package com.bleelblep.sparkle",
		"",
		"internal object BossData {",
		"\tclass Pet(override val id: String, override val name: String, override val w: Int, override val h: Int,",
		"\t\toverride val strips: Map<String, Pair<Int, Array<String>>>, override val mouth: FloatArray?,",
		"\t\toverride val refW: Int, override val idleFps: Float) : SheetPet",
		"",
		"\t/** The playable pets, after SeasonalData's in Looks: ids " + ", ".join(str(first_id + i) for i in range(len(BOSSES))) + ". */",
		"\tval pets: List<Pet> = listOf(",
	]
	records = []
	for i, (pid, name, pack, default_name, leaves, mouth, ref_w, idle_fps, make) in enumerate(BOSSES):
		anims = make()
		body, size = pet_lines(pid, name, anims, mouth, ref_w, idle_fps)
		lines += body
		records.append(dict(id=first_id + i, label=name, pack=pack, kind="seasonal", defaultName=default_name, bubbles="bubbles", leaves=leaves))
		print(f"{pid}: id {first_id + i}, {size[0]}x{size[1]}, {len(anims)} strips")
	lines.append("\t)")
	lines.append("")
	lines.append("\t/** The Horseman's horse: not a pet of its own; the companion visit and the ride draw it. */")
	horse_anims = boss_art.horse_anims()
	hb, hs = pet_lines("horse", "The horse", horse_anims, None, 64, 4.0)
	lines.append("\tval horse: Pet =")
	lines += ["\t" + l for l in hb]
	lines[-1] = lines[-1].rstrip(",")
	lines += ["}", ""]
	KT.write_text("\n".join(lines), encoding="utf-8")
	print(f"wrote {KT.name}: {KT.stat().st_size // 1024} KB; horse {hs[0]}x{hs[1]}, {len(horse_anims)} strips")

	TS.write_text("// Generated by tools/build_boss.py.\nexport const BOSS_PETS = " + json.dumps(records, indent=2) + " as const\n", encoding="utf-8")
	print(f"wrote {TS.name}")


if __name__ == "__main__":
	main()
