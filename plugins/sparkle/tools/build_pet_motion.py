"""Embed art/pet_motion strips; each breed has its own initializer to limit bytecode size."""
import base64
import json
from pathlib import Path
from PIL import Image

ROOT=Path(__file__).resolve().parent.parent
ART=ROOT/'art/pet_motion'
OUT=ROOT/'src/main/kotlin/com/bleelblep/sparkle/PetMotionData.kt'
records=json.loads((ART/'manifest.json').read_text())
lines=['// GENERATED by tools/build_pet_motion.py. LuizMelo pet art, CC0.',
       'package com.bleelblep.sparkle','', 'internal object PetMotionData {',
       '\tclass Strip(val times: IntArray, val loop: Boolean, val png: Array<String>)',
       '\tclass Pet(val w: Int, val h: Int, val mouthX: Float, val mouthY: Float, val strips: Map<String, Strip>)',
       '\tfun of(id: String): Pet = when (id) {']
for i,r in enumerate(records):lines.append(f'\t\t"{r["id"]}" -> PetMotion{i}.pet')
lines+=['\t\telse -> error("Unknown pet motion: $id")','\t}', '}']
for i,r in enumerate(records):
    lines += [f'private object PetMotion{i} {{',f'\tval pet = PetMotionData.Pet({r["w"]}, {r["h"]}, {r["mouth"][0]}f, {r["mouth"][1]}f, mapOf(']
    assert len(r['animations'])==24
    for a in r['animations']:
        path=ART/r['id']/(a['name']+'.png')
        with Image.open(path) as im:assert im.size==(r['w']*len(a['times']),r['h'])
        data=base64.b64encode(path.read_bytes()).decode('ascii')
        chunks=', '.join('"'+data[x:x+50000]+'"' for x in range(0,len(data),50000))
        times=', '.join(map(str,a['times']))
        lines.append(f'\t\t"{a["name"]}" to PetMotionData.Strip(intArrayOf({times}), {str(a["loop"]).lower()}, arrayOf({chunks})),')
    lines+=['\t))','}']
OUT.write_text('\n'.join(lines)+'\n',encoding='utf-8')
print('Embedded 288 animation strips across 12 breeds.')
