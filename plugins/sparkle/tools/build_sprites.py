"""Regenerates src/main/kotlin/.../SpriteData.kt from sprites/<animation>/*.png.

Every frame is placed on ONE shared cell, bottom-centred, so the unicorn keeps its size and its feet
stay put from frame to frame and from one animation to the next (the source frames were cut to their
own bounding boxes, so drawn as-is they would jitter). Each animation becomes a single horizontal
strip PNG, embedded as base64 like VFX's sounds: plugin zips carry only manifest.json, index.js and
plugin.jar.

Single images in fx/ (the bubble and its pop) are embedded at their own size, untouched by the
shared cell, as `images`.

Run from the plugin folder:  python tools/build_sprites.py   (needs Pillow)
"""
import base64
import io
import pathlib

from PIL import Image

HERE = pathlib.Path(__file__).resolve().parent.parent
SRC = HERE / "sprites"
OUT = HERE / "src/main/kotlin/com/bleelblep/sparkle/SpriteData.kt"
CHUNK = 60000

anims = {}
for folder in sorted(p for p in SRC.iterdir() if p.is_dir()):
    frames = [Image.open(f).convert("RGBA") for f in sorted(folder.glob("*.png"))]
    if frames:
        anims[folder.name] = frames

cell_w = max(f.width for fs in anims.values() for f in fs)
cell_h = max(f.height for fs in anims.values() for f in fs)

lines = [
    "// GENERATED by tools/build_sprites.py from sprites/ -- do not edit by hand.",
    "",
    "package com.bleelblep.sparkle",
    "",
    "internal object SpriteData {",
    f"\tconst val CELL_W = {cell_w}",
    f"\tconst val CELL_H = {cell_h}",
    "",
    "\t/** Animation name -> (frame count, base64 PNG strip chunks joined in order). Frames sit side by side. */",
    "\tval strips: Map<String, Pair<Int, Array<String>>> = mapOf(",
]
total = 0
for name, frames in anims.items():
    strip = Image.new("RGBA", (cell_w * len(frames), cell_h), (0, 0, 0, 0))
    for i, f in enumerate(frames):
        strip.paste(f, (i * cell_w + (cell_w - f.width) // 2, cell_h - f.height), f)
    buf = io.BytesIO()
    # Pixel art uses few colours: a palette PNG is a fraction of the size, with alpha kept.
    strip.quantize(colors=128, method=Image.Quantize.FASTOCTREE).save(buf, "PNG", optimize=True)
    data = base64.b64encode(buf.getvalue()).decode("ascii")
    total += len(data)
    chunks = [data[i : i + CHUNK] for i in range(0, len(data), CHUNK)]
    body = ", ".join(f'"{c}"' for c in chunks)
    lines.append(f'\t\t"{name}" to ({len(frames)} to arrayOf({body})),')
lines += ["\t)", "", "\t/** Effect images (fx/), name -> base64 PNG chunks. Their own size, not the shared cell. */"]
lines.append("\tval images: Map<String, Array<String>> = mapOf(")
for path in sorted((HERE / "fx").glob("*.png")):
    buf = io.BytesIO()
    Image.open(path).convert("RGBA").quantize(colors=128, method=Image.Quantize.FASTOCTREE).save(buf, "PNG", optimize=True)
    data = base64.b64encode(buf.getvalue()).decode("ascii")
    total += len(data)
    chunks = [data[i : i + CHUNK] for i in range(0, len(data), CHUNK)]
    body = ", ".join(f'"{c}"' for c in chunks)
    lines.append(f'\t\t"{path.stem}" to arrayOf({body}),')
lines += ["\t)", "}", ""]
OUT.write_text("\n".join(lines), encoding="utf-8")
print(f"wrote {OUT.relative_to(HERE)}: {len(anims)} animations, cell {cell_w}x{cell_h}, {total // 1024} KB base64")
